export function isSupportedLanguage(value: string | null | undefined): value is Language {
  return value === "English" || value === "Mandarin" || value === "Spanish";
}

export function detectBrowserLanguage(browserLanguage?: string): Language {
  const normalized = (browserLanguage ?? "").toLowerCase();
  if (normalized.startsWith("zh")) {
    return "Mandarin";
  }
  if (normalized.startsWith("es")) {
    return "Spanish";
  }
  return "English";
}

export function getLanguageMeta(language: Language) {
  return languageOptions.find((option) => option.value === language) ?? languageOptions[0];
}

